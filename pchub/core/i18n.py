def systemLanguage():
    return "it" if QLocale.system().name().lower().startswith("it") else "en"


def setLanguage(languageCode):
    global _currentLanguage
    if languageCode in (None, "", "auto"):
        languageCode = systemLanguage()
    _currentLanguage = languageCode if languageCode in STRINGS else "en"


def language():
    return _currentLanguage


def tr(textKey, **formatArgs):
    if textKey is None:
        return ""
    if isinstance(textKey, dict):
        text = textKey.get(_currentLanguage) or textKey.get("en") or textKey.get("it") or next(iter(textKey.values()), "")
    else:
        text = STRINGS.get(_currentLanguage, {}).get(textKey)
        if text is None:
            text = STRINGS["en"].get(textKey, textKey)
    if formatArgs:
        try:
            text = text.format(**formatArgs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def formatBytes(byteCount):
    byteCount = float(byteCount or 0)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if abs(byteCount) < 1024 or unit == "TB":
            if unit == "B":
                return f"{int(byteCount)} {unit}"
            return f"{byteCount:.1f} {unit}".replace(".", "," if _currentLanguage == "it" else ".")
        byteCount /= 1024
    return f"{byteCount:.1f} TB"


def formatNumber(value):
    text = f"{int(value):,}"
    return text.replace(",", ".") if _currentLanguage == "it" else text


def formatDuration(totalSeconds, showHours=None):
    totalSeconds = max(0, int(round(totalSeconds)))
    hours, remainder = divmod(totalSeconds, 3600)
    minutes, seconds = divmod(remainder, 60)
    if hours or showHours:
        return f"{hours}:{minutes:02d}:{seconds:02d}"
    return f"{minutes:02d}:{seconds:02d}"
